/** The texts of one chart: title, average-set-weight line, summary readout and one readout per bar. */
private data class ChartTexts(
    val title: String,
    val averageLine: String,
    val summary: String,
    val readouts: List<String>,
)

/**
 * Every chart title and readout must read exactly like the prototype's (testdata/progress-golden.json,
 * generated by running the prototype headless). Runs on a device because the text comes from string resources.
 */
@RunWith(AndroidJUnit4::class)
class ProgressTextGoldenTest {
    @get:Rule
    val compose = createComposeRule()

    @Test
    fun everyTitleAndReadoutMatchesThePrototype() {
        val golden = loadGolden()
        val today = LocalDate.parse(golden.string("today"))
        val bodyweightKg = golden.getValue("bodyweight").jsonPrimitive.double
        val entries = golden.getValue("entries").jsonArray.map { element ->
            val text = element.jsonObject.string("text")
            JournalEntry(LocalDate.parse(element.jsonObject.string("date")), text, EntryParser.parse(text))
        }
        val cases = golden.getValue("cases").jsonArray.map { it.jsonObject }
        val charts = cases.map {
            periodStats(it.period(), entries, today, bodyweightKg).chart(it.view(), it.exercise())
        }
        val actual = arrayOfNulls<ChartTexts>(cases.size)

        compose.setContent {
            LiftJournalTheme(LightPalette) {
                charts.forEachIndexed { index, chart -> actual[index] = chartTexts(chart, today) }
            }
        }
        compose.waitForIdle()

        cases.forEachIndexed { index, case ->
            val name = "${case.string("period")} ${case.string("view")} ${case.exercise().orEmpty()}"
            val texts = requireNotNull(actual[index])
            assertEquals("$name: title", case.string("title"), texts.title)
            assertEquals("$name: average line", case.string("avgLine"), texts.averageLine)
            assertEquals("$name: summary", case.string("summary"), texts.summary)
            assertEquals(
                "$name: readouts",
                case.getValue("readouts").jsonArray.map {
                    it.jsonPrimitive.content
                },
                texts.readouts,
            )
        }
    }

    @Composable
    private fun chartTexts(chart: ProgressChart, today: LocalDate) = ChartTexts(
        title = chartTitle(chart),
        averageLine = averageSetWeightLine(chart)?.text.orEmpty(),
        summary = readoutText(chart, null, today)?.text.orEmpty(),
        readouts = barIndices(chart).map { readoutText(chart, it, today)?.text.orEmpty() },
    )

    private fun barIndices(chart: ProgressChart): IntRange = when (chart) {
        is ProgressChart.NoExercise -> IntRange.EMPTY
        is ProgressChart.Months -> chart.bars.indices
        is ProgressChart.Weeks -> chart.bars.indices
        is ProgressChart.Years -> chart.bars.indices
    }

    private fun loadGolden(): JsonObject {
        val assets = InstrumentationRegistry.getInstrumentation().context.assets
        val text = assets.open("progress-golden.json").bufferedReader().use { it.readText() }
        return Json.parseToJsonElement(text).jsonObject
    }

    private fun JsonObject.string(key: String): String = getValue(key).jsonPrimitive.content

    private fun JsonObject.period(): ProgressPeriod =
        string("period").toIntOrNull()?.let { ProgressPeriod.OneYear(it) } ?: ProgressPeriod.AllTime

    private fun JsonObject.view(): ProgressView = when (string("view")) {
        "top" -> ProgressView.TOP_SET
        "exmonth" -> ProgressView.EXERCISE_VOLUME
        else -> ProgressView.TOTAL_VOLUME
    }

    private fun JsonObject.exercise(): String? = getValue("exercise").jsonPrimitive.contentOrNull
}
