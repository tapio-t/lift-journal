/**
 * Release signing comes from keystore.properties at the repository root, which is git-ignored together with
 * the keystore itself. Without it, release builds are simply unsigned. See keystore.properties.example.
 */
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.example.liftjournal"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.example.liftjournal"
        minSdk = 26
        targetSdk = 36
        // Versioning: versionName is semantic (major.minor.patch); versionCode goes up by one per release.
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (!keystoreProperties.isEmpty) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    sourceSets {
        // Room's exported schemas are needed by migration tests.
        getByName("androidTest").assets.directories.add("$projectDir/schemas")
        // Golden parser cases and sample files are shared with the prototype in /testdata.
        getByName("test").resources.directories.add("$rootDir/testdata")
        // Device tests check Progress text (string resources) against the same golden data.
        getByName("androidTest").assets.directories.add("$rootDir/testdata")
    }

    lint {
        abortOnError = true
        disable += setOf("GradleDependency", "NewerVersionAvailable", "AndroidGradlePluginVersion")
    }
}

ksp {
    arg("room.schemaLocation", "$projectDir/schemas")
